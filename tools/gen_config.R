#!/usr/bin/env Rscript
# =============================================================================
# gen_config.R — turn config/knobs.json into the files that consume it
# =============================================================================
#   config/knobs.generated.sh        defaults the entrypoint sources
#   docs/routine_config.schema.json  the Routine Configuration Schema for WKUBE
#   config/config.json               active default configuration instance
# Run after editing the registry:    Rscript tools/gen_config.R
# =============================================================================
j <- function(f) jsonlite::fromJSON(f, simplifyVector = FALSE)
if (!requireNamespace('jsonlite', quietly = TRUE)) {
  stop('jsonlite is needed to regenerate the config; please install it.')
}

reg <- j('config/knobs.json')$knobs
nm  <- vapply(reg, `[[`, '', 'name')
esc <- function(x) gsub("'", "'\\\\''", x)

# ---- dynamic folder auto-discovery helpers ---------------------------------
scan_macro_outputs <- function(fallback_enums = character(0)) {
  dirs <- c(
    "W:/model_outputs", "W:/model_outputs/merged",
    "/mnt/wdrv/model_outputs", "/mnt/wdrv/model_outputs/merged",
    "inputs"
  )
  dirs <- dirs[dir.exists(dirs)]
  files <- character(0)
  for (d in dirs) {
    found <- list.files(d, pattern = "\\.(csv|parquet)$", recursive = TRUE, full.names = FALSE)
    files <- c(files, basename(found))
  }
  files <- unique(files[!grepl("sample|temp", files, ignore.case = TRUE)])
  if (length(files) > 0) {
    # Order by extracted 8-digit date stamp desc, then alphabetical
    ord <- order(ifelse(grepl("^[0-9]{8}", files), substr(files, 1, 8), ""), files, decreasing = TRUE)
    files <- files[ord]
    return(unique(c("latest", files, fallback_enums)))
  }
  if (length(fallback_enums) > 0) fallback_enums else "latest"
}

scan_downscale_outputs <- function(fallback_enums = character(0)) {
  dirs <- c(
    "W:/cascade_gamble_outputs",
    "/mnt/wdrv/cascade_gamble_outputs",
    "outputs"
  )
  dirs <- dirs[dir.exists(dirs)]
  cands <- character(0)
  for (d in dirs) {
    found <- list.files(d, pattern = "^DS_ACT4CAP_", full.names = FALSE)
    cands <- c(cands, basename(found))
  }
  cands <- unique(cands)
  cands <- cands[!grepl("_luc|smoke", cands, ignore.case = TRUE)]
  if (length(cands) > 0) {
    cands <- sort(cands, decreasing = TRUE)
    return(unique(c("auto", cands, fallback_enums, "none")))
  }
  if (length(fallback_enums) > 0) fallback_enums else c("auto", "none")
}

# ---- shell registry ---------------------------------------------------------
sh <- c(
  '# GENERATED by tools/gen_config.R from config/knobs.json -- do not edit.',
  '# Edit the registry and re-run the generator.',
  '',
  sprintf('KNOB_REGISTRY=(%s)', paste(sprintf("'%s'", nm), collapse = ' '))
)
for (k in reg) {
  sh <- c(sh,
    sprintf("KNOB_ENV_%s='%s'",     k$name, esc(if (nzchar(k$env)) k$env else k$name)),
    sprintf("KNOB_DEFAULT_%s='%s'", k$name, esc(k$default)),
    sprintf("KNOB_BLANK_%s='%s'",   k$name, esc(k$blank)),
    sprintf("KNOB_SCOPE_%s='%s'",   k$name, esc(k$scope))
  )
}
writeLines(sh, 'config/knobs.generated.sh')

# ---- routine configuration schema -------------------------------------------
props <- lapply(reg, function(k) {
  blank <- !nzchar(k$default)
  desc  <- sprintf('%s -- %s', if (nzchar(k$label)) k$label else k$name, k$desc)
  if (blank) desc <- sprintf('%s OPTIONAL: leave empty for %s.', desc,
                             if (nzchar(k$blank)) k$blank else 'the built-in default')
  p <- list(
    type = k$type,
    title = if (nzchar(k$label)) k$label else k$name,
    description = desc,
    default = k$default
  )
  # Dynamic scanning for target folder outputs
  if (k$name == "INPUT_FILE") {
    p$enum <- scan_macro_outputs(if (!is.null(k$enum)) unlist(k$enum) else character(0))
  } else if (k$name == "DOWNSCALE_OUTPUT") {
    p$enum <- scan_downscale_outputs(if (!is.null(k$enum)) unlist(k$enum) else character(0))
  } else if (!is.null(k$enum)) {
    p$enum <- k$enum
  }
  p
})
names(props) <- nm

schema <- list(root = list(
  type = 'object',
  title = 'Act4Cap Integrated Downscaling & Environmental Routine Configuration',
  description = paste(
    'GENERATED from config/knobs.json by tools/gen_config.R.',
    'Executes Cascading Gamble spatial downscaling across EU-27 for selected macro models',
    '(GLOBIOM, CAPRI, IMAGE, MAGNET, CLUMONDO), followed by SWAT+ water quality simulations',
    'and Biodiversity Link ecological metrics in a cluster container environment. Entrypoint: entrypoint.sh.'
  ),
  required = list('TASK', 'MACRO_MODEL'),
  properties = props
))

jsonlite::write_json(schema, 'docs/routine_config.schema.json',
                     auto_unbox = TRUE, pretty = TRUE, null = 'null')

# ---- default active config.json --------------------------------------------
default_cfg <- list()
for (k in reg) {
  default_cfg[[k$name]] <- k$default
}
jsonlite::write_json(default_cfg, 'config/config.json',
                     auto_unbox = TRUE, pretty = TRUE)

cat(sprintf('Wrote config/knobs.generated.sh (%d knobs), docs/routine_config.schema.json, and config/config.json\n', length(reg)))
